// These commands are hand-written (not generated by Speakeasy). They replace
// the generated `auth login` and `auth logout`: initAuthCmd in auth.go only
// adds a subcommand when none of that name exists yet, so registering these
// first - see initCustomAuthCmds in root.go - is what makes them win.
//
// The generated login asks the user to paste an API key. This one signs the
// user in through the browser (OAuth device flow against Auth0), then uses
// the resulting token once, to mint an API key named after this machine,
// and stores that key exactly where the generated command would have. The
// token itself is never written anywhere. Everything downstream - every
// generated command, --dry-run, --no-keyring, SHADEFORM_API_KEY - sees the
// same single credential it always did.

const (
	loginNameFlag        = "name"
	loginPermissionsFlag = "permissions"
	loginNoBrowserFlag   = "no-browser"
	logoutKeepRemoteFlag = "keep-remote"

	// loginKeyPrefix is how keys minted here are named in the dashboard, so
	// a person can tell them from keys they created by hand.
	loginKeyPrefix = "shade CLI"
)

// initCustomAuthCmds registers the auth group and the hand-written login
// and logout under it. It must run before initAuthCmd.
func initCustomAuthCmds(parent *cobra.Command) error {
	var authCmd *cobra.Command
	for _, existing := range parent.Commands() {
		if existing.Name() == "auth" {
			authCmd = existing
			break
		}
	}
	if authCmd == nil {
		authCmd = &cobra.Command{
			Use:   "auth",
			Short: "Manage authentication credentials",
			Long: `Manage authentication credentials for shade.

Subcommands:
  login   - Sign in through your browser and store an API key for this machine
  whoami  - Display current authentication status
  logout  - Revoke this machine's API key and clear stored credentials`,
		}
		parent.AddCommand(authCmd)
	}

	login := &cobra.Command{
		Use:   "login",
		Short: "Sign in through your browser and store an API key for this machine",
		Long: `Sign in to Shadeform from the terminal.

shade opens your browser to confirm a short code. Once you approve, it
creates an API key for this machine - named "` + loginKeyPrefix + ` (<hostname>)" so
you can recognise it under Settings > API Keys - and stores it in the OS
keychain (or ~/.config/shade/config.yaml with --no-keyring). Nothing else
is stored: the browser sign-in is used once and forgotten.

Signing in again on the same machine replaces the previous key. To use a
key you already have instead, pass --api-key; nothing is opened and no key
is created.

On a machine without a browser, open the printed URL anywhere and enter the
code there.`,
		Example: `  shade auth login
  shade auth login --no-browser
  shade auth login --name "shade CLI (build box)"
  shade auth login --api-key sk_live_xxxxxxxx`,
		Annotations: map[string]string{"speakeasy_settings_command": "true"},
		Args:        cobra.NoArgs,
		RunE:        runLoginCmd,
	}
	login.Flags().String(loginNameFlag, "", "Name for the API key as shown in the dashboard (default \""+loginKeyPrefix+" (<hostname>)\")")
	login.Flags().String(loginPermissionsFlag, strings.Join(apikeys.DefaultPermissions, ","),
		"Comma-separated permissions for the key: platform_read, platform_write, billing_read, billing_write")
	login.Flags().Bool(loginNoBrowserFlag, false, "Print the sign-in URL and code instead of opening a browser")
	authCmd.AddCommand(login)
	usage.RegisterCustomCommand(login, "auth")

	logout := &cobra.Command{
		Use:   "logout",
		Short: "Revoke this machine's API key and clear stored credentials",
		Long: `Sign out of Shadeform on this machine.

If the stored API key was created by "shade auth login", it is revoked on
the server first, so it stops working everywhere, not just here. Then the
key is removed from the OS keychain and the config file.

A key you pasted with --api-key is only removed locally; it stays valid in
the dashboard because shade did not create it.`,
		Example: `  shade auth logout
  shade auth logout --keep-remote`,
		Annotations: map[string]string{"speakeasy_settings_command": "true"},
		Args:        cobra.NoArgs,
		RunE:        runLogoutCmd,
	}
	logout.Flags().Bool(logoutKeepRemoteFlag, false, "Clear local credentials only; leave the API key valid on the server")
	authCmd.AddCommand(logout)
	usage.RegisterCustomCommand(logout, "auth")
	return nil
}

// loginResult is what login reports, in prose or as JSON.
type loginResult struct {
	Method      string   `json:"method"`
	APIKeyID    string   `json:"api_key_id,omitempty"`
	APIKeyName  string   `json:"api_key_name,omitempty"`
	Permissions []string `json:"permissions,omitempty"`
	StoredIn    string   `json:"stored_in"`
	ConfigFile  string   `json:"config_file"`
	Replaced    string   `json:"replaced_api_key_id,omitempty"`
}

func runLoginCmd(cmd *cobra.Command, args []string) error {
	if usage.UsageRequested(cmd) {
		return usage.EmitSchema(cmd, cmd.OutOrStdout())
	}
	if dryRunLocalNoop(cmd, "auth login changes local credentials only (no API request); nothing was changed.") {
		return nil
	}
	cfg := config.GetConfig()
	if cfg == nil {
		cfg = &config.Config{}
	}

	// Paste path: an explicit --api-key is stored as-is, as the generated
	// command did. No browser, no key minted, and any previous login's key
	// is left alone - the user chose a credential, not a sign-in.
	if f := cmd.Flags().Lookup("api-key"); f != nil && f.Changed {
		key, _ := cmd.Flags().GetString("api-key")
		if strings.TrimSpace(key) == "" {
			return flagutil.WithCLIValidation(errors.New("--api-key was given but empty"))
		}
		storedIn := storeAPIKey(cfg, key)
		if err := config.SaveConfig(cfg); err != nil {
			return fmt.Errorf("failed to save configuration: %w", err)
		}
		// This key was not minted by login, so a stale login record would
		// make logout revoke the wrong thing.
		_ = loginstate.Clear(config.GetConfigPath())
		return reportLogin(cmd, loginResult{Method: "api-key", StoredIn: storedIn, ConfigFile: config.GetConfigPath()})
	}

	permissions, err := parsePermissions(cmd)
	if err != nil {
		return err
	}
	name, _ := flagutil.GetStringFlag(cmd, loginNameFlag)
	if name == "" {
		name = defaultKeyName()
	}
	noBrowser, _ := flagutil.GetBoolFlag(cmd, loginNoBrowserFlag)
	serverURL := resolveServerURL(cmd)
	ctx := cmd.Context()
	if ctx == nil {
		ctx = context.Background()
	}
	errOut := cmd.ErrOrStderr()

	// 1. Browser sign-in.
	auth := auth0device.DefaultConfig()
	code, err := auth.RequestDeviceCode(ctx)
	if errors.Is(err, auth0device.ErrNotConfigured) {
		return fmt.Errorf("browser sign-in is not available in this build; use --api-key with a key from Settings > API Keys (%w)", err)
	}
	if err != nil {
		return err
	}
	fmt.Fprintf(errOut, "Confirm this code in your browser: %s\n", code.UserCode)
	opened := false
	if !noBrowser {
		opened = auth0device.OpenBrowser(code.VerificationURIComplete) == nil
	}
	if opened {
		fmt.Fprintf(errOut, "If the browser did not open, visit %s\n", code.VerificationURIComplete)
	} else {
		fmt.Fprintf(errOut, "Open %s\n", code.VerificationURIComplete)
	}
	fmt.Fprintln(errOut, "Waiting for sign-in...")
	token, err := auth.Poll(ctx, code)
	if err != nil {
		return fmt.Errorf("sign-in did not complete: %w", err)
	}

	// 2. Mint a key with the token, which is then dropped.
	api := apikeys.NewWithBearer(serverURL, token.AccessToken)
	token = nil

	previous, _ := loginstate.Load(config.GetConfigPath())
	replaced := ""
	if previous != nil && previous.APIKeyID != "" {
		if err := api.Delete(ctx, previous.APIKeyID); err != nil {
			fmt.Fprintf(errOut, "Warning: could not revoke the previous key %s (%v); it is still listed in the dashboard.\n", previous.APIKeyID, err)
		} else {
			replaced = previous.APIKeyID
		}
	}

	existing, err := api.List(ctx)
	if err != nil {
		if apikeys.IsUnauthorized(err) {
			return fmt.Errorf("signed in, but the API did not accept the token: %w\nIf this account was created moments ago, finish onboarding at https://platform.shadeform.ai first", err)
		}
		return err
	}
	name = uniqueKeyName(name, existing)
	if len(existing) >= apikeys.MaxKeysPerAccount {
		names := make([]string, 0, len(existing))
		for _, k := range existing {
			names = append(names, k.Name)
		}
		return fmt.Errorf("this account already has %d API keys, the maximum. Delete one under Settings > API Keys and sign in again. Existing keys: %s",
			len(existing), strings.Join(names, ", "))
	}
	created, err := api.Create(ctx, name, permissions)
	if err != nil {
		return err
	}

	// 3. Store the key where every other command reads it.
	storedIn := storeAPIKey(cfg, created.APIKey)
	if err := config.SaveConfig(cfg); err != nil {
		return fmt.Errorf("the key %q was created but the configuration could not be saved: %w\nRevoke it under Settings > API Keys", created.Name, err)
	}
	if err := loginstate.Save(config.GetConfigPath(), loginstate.State{
		APIKeyID:   created.ID,
		APIKeyName: created.Name,
		ServerURL:  serverURL,
		LoggedInAt: time.Now().UTC(),
	}); err != nil {
		fmt.Fprintf(errOut, "Warning: %v; logout will not be able to revoke this key automatically.\n", err)
	}
	return reportLogin(cmd, loginResult{
		Method:      "browser",
		APIKeyID:    created.ID,
		APIKeyName:  created.Name,
		Permissions: created.Permissions,
		StoredIn:    storedIn,
		ConfigFile:  config.GetConfigPath(),
		Replaced:    replaced,
	})
}

// logoutResult is what logout reports, in prose or as JSON.
type logoutResult struct {
	RevokedAPIKeyID string `json:"revoked_api_key_id,omitempty"`
	RevokeSkipped   string `json:"revoke_skipped,omitempty"`
	ClearedKeyring  bool   `json:"cleared_keyring"`
	ConfigFile      string `json:"config_file"`
}

func runLogoutCmd(cmd *cobra.Command, args []string) error {
	if usage.UsageRequested(cmd) {
		return usage.EmitSchema(cmd, cmd.OutOrStdout())
	}
	if dryRunLocalNoop(cmd, "auth logout removes local credentials only (no API request); nothing was changed.") {
		return nil
	}
	cfg := config.GetConfig()
	if cfg == nil {
		cfg = &config.Config{}
	}
	ctx := cmd.Context()
	if ctx == nil {
		ctx = context.Background()
	}
	keepRemote, _ := flagutil.GetBoolFlag(cmd, logoutKeepRemoteFlag)
	res := logoutResult{ConfigFile: config.GetConfigPath()}

	// Revoke first, while the key is still at hand to authenticate with.
	state, _ := loginstate.Load(config.GetConfigPath())
	switch {
	case state == nil:
		res.RevokeSkipped = "no key was created by shade auth login on this machine"
	case keepRemote:
		res.RevokeSkipped = "--keep-remote"
	default:
		key, _ := config.ResolveRequestSecurityCredential(cmd, "api-key")
		if key == "" {
			res.RevokeSkipped = "no stored API key to authenticate the revocation with"
			break
		}
		serverURL := state.ServerURL
		if serverURL == "" {
			serverURL = resolveServerURL(cmd)
		}
		if err := apikeys.NewWithAPIKey(serverURL, key).Delete(ctx, state.APIKeyID); err != nil {
			if apikeys.IsUnauthorized(err) {
				// The key is already dead on the server; nothing to revoke.
				res.RevokedAPIKeyID = state.APIKeyID
			} else {
				return fmt.Errorf("%w\nUse --keep-remote to clear local credentials anyway, then delete the key under Settings > API Keys", err)
			}
		} else {
			res.RevokedAPIKeyID = state.APIKeyID
		}
	}

	if config.KeyringAvailable() {
		_ = config.DeleteKeyringValue("api-key")
		res.ClearedKeyring = true
	}
	cfg.Security.ApiKey = ""
	if err := config.SaveConfig(cfg); err != nil {
		return fmt.Errorf("failed to save configuration: %w", err)
	}
	if err := loginstate.Clear(config.GetConfigPath()); err != nil {
		return err
	}

	if output.IsMachineMode(cmd) {
		// A map, not the struct: the output layer treats a struct as an
		// SDK response envelope and unwraps its first field.
		return output.LocalResult(cmd, asMap(res))
	}
	out := cmd.OutOrStdout()
	if res.RevokedAPIKeyID != "" {
		fmt.Fprintf(out, "Revoked API key %s on the server.\n", res.RevokedAPIKeyID)
	} else if state != nil && res.RevokeSkipped != "" {
		fmt.Fprintf(out, "API key %s was not revoked (%s); it is still valid in the dashboard.\n", state.APIKeyID, res.RevokeSkipped)
	}
	if res.ClearedKeyring {
		fmt.Fprintln(out, "All authentication credentials have been cleared.")
	} else {
		fmt.Fprintln(out, "Authentication credentials have been cleared from the config file; the OS keychain was skipped, so credentials stored there (if any) were kept.")
	}
	fmt.Fprintf(out, "Configuration saved to %s\n", res.ConfigFile)
	return nil
}

// storeAPIKey puts the key in the keychain, or the config file when the
// keychain is unavailable or disabled, and says which.
func storeAPIKey(cfg *config.Config, key string) string {
	if config.StoreSecret("api-key", key, &cfg.Security.ApiKey) == nil {
		return "keyring"
	}
	return "config"
}

func reportLogin(cmd *cobra.Command, res loginResult) error {
	if output.IsMachineMode(cmd) {
		return output.LocalResult(cmd, asMap(res))
	}
	out := cmd.OutOrStdout()
	if res.Method == "browser" {
		fmt.Fprintf(out, "Signed in. Created API key %q (%s) with permissions %s.\n",
			res.APIKeyName, res.APIKeyID, strings.Join(res.Permissions, ", "))
		if res.Replaced != "" {
			fmt.Fprintf(out, "Revoked the previous key %s.\n", res.Replaced)
		}
	}
	if res.StoredIn == "keyring" {
		fmt.Fprintln(out, "Secret credentials stored in OS keychain")
	}
	fmt.Fprintf(out, "Configuration saved to %s\n", res.ConfigFile)
	return nil
}

// asMap round-trips a result through JSON so the output layer sees a plain
// object; it unwraps the first field of any struct it is handed.
func asMap(v any) map[string]any {
	b, err := json.Marshal(v)
	if err != nil {
		return map[string]any{"error": err.Error()}
	}
	var m map[string]any
	_ = json.Unmarshal(b, &m)
	return m
}

func parsePermissions(cmd *cobra.Command) ([]string, error) {
	raw, _ := flagutil.GetStringFlag(cmd, loginPermissionsFlag)
	allowed := map[string]bool{
		apikeys.PermissionPlatformRead:  true,
		apikeys.PermissionPlatformWrite: true,
		apikeys.PermissionBillingRead:   true,
		apikeys.PermissionBillingWrite:  true,
	}
	var out []string
	seen := map[string]bool{}
	for _, p := range strings.Split(raw, ",") {
		p = strings.TrimSpace(p)
		if p == "" || seen[p] {
			continue
		}
		if !allowed[p] {
			return nil, flagutil.WithCLIValidation(fmt.Errorf("unknown permission %q; choose from platform_read, platform_write, billing_read, billing_write", p))
		}
		seen[p] = true
		out = append(out, p)
	}
	if len(out) == 0 {
		return nil, flagutil.WithCLIValidation(errors.New("--permissions must name at least one permission"))
	}
	return out, nil
}

// defaultKeyName names the key after this machine, which is what a person
// scanning the dashboard needs to know about it.
func defaultKeyName() string {
	host, err := os.Hostname()
	if err != nil || host == "" {
		host = "this machine"
	}
	host = strings.TrimSuffix(host, ".local")
	return loginKeyPrefix + " (" + host + ")"
}

// uniqueKeyName appends a timestamp when the name is already taken, since
// the server refuses duplicates. Happens when a previous login's key could
// not be revoked, or the user made one with the same name by hand.
func uniqueKeyName(name string, existing []apikeys.Key) string {
	taken := map[string]bool{}
	for _, k := range existing {
		taken[k.Name] = true
	}
	if !taken[name] {
		return name
	}
	return name + " " + time.Now().UTC().Format("2006-01-02 15:04")
}

// resolveServerURL mirrors how client.NewClient picks the server, so the
// key is minted on the same API the generated commands will call.
func resolveServerURL(cmd *cobra.Command) string {
	if v, _ := flagutil.GetStringFlag(cmd, "server-url"); v != "" {
		return v
	}
	return sdk.ServerList[0]
}
