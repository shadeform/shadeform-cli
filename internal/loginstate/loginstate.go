// Package loginstate remembers which API key `shade auth login` minted, so a
// later login can replace it and logout can revoke it.
//
// It is a separate file next to config.yaml rather than new fields on the
// generated Config struct: that struct is rewritten by every regeneration
// and re-marshalled by every `shade configure`, which would drop fields it
// does not know about. Nothing here is secret - the key itself lives in the
// OS keychain (or config.yaml with --no-keyring); this is only its ID and
// name as the dashboard shows them.
//
// This package is hand-written, not generated by Speakeasy.
package loginstate

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"gopkg.in/yaml.v3"
)

// FileName sits beside config.yaml in the CLI's config directory.
const FileName = "login.yaml"

// State describes the key the last successful login produced.
type State struct {
	APIKeyID   string    `yaml:"api_key_id"`
	APIKeyName string    `yaml:"api_key_name"`
	ServerURL  string    `yaml:"server_url,omitempty"`
	LoggedInAt time.Time `yaml:"logged_in_at"`
}

// Path returns the file's location given the config file's path, so the
// two always share a directory whatever the config package decides.
func Path(configPath string) string {
	if configPath == "" {
		return ""
	}
	return filepath.Join(filepath.Dir(configPath), FileName)
}

// Load reads the state. A missing file is not an error: it returns nil, nil.
func Load(configPath string) (*State, error) {
	p := Path(configPath)
	if p == "" {
		return nil, nil
	}
	data, err := os.ReadFile(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", p, err)
	}
	var s State
	if err := yaml.Unmarshal(data, &s); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", p, err)
	}
	if s.APIKeyID == "" {
		return nil, nil
	}
	return &s, nil
}

// Save writes the state with the same permissions config.yaml uses.
func Save(configPath string, s State) error {
	p := Path(configPath)
	if p == "" {
		return errors.New("no config directory to write login state to")
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Dir(p), err)
	}
	data, err := yaml.Marshal(s)
	if err != nil {
		return err
	}
	if err := os.WriteFile(p, data, 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", p, err)
	}
	return nil
}

// Clear removes the file. Absent is fine.
func Clear(configPath string) error {
	p := Path(configPath)
	if p == "" {
		return nil
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("removing %s: %w", p, err)
	}
	return nil
}
